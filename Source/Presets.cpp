// Favourites.json: { "format": 1, "factory": [names], "user": [names] } (as in the other plug-ins of the series).
namespace
{
juce::String favouriteKey (const Kit& k) { return (k.isFactory() ? "F|" : "U|") + k.name; }

juce::StringArray readFavourites (const juce::File& file)
{
    juce::StringArray keys;
    const auto json = juce::JSON::parse (file.loadFileAsString());
    if (auto* obj = json.getDynamicObject())
        for (auto [field, prefix] : { std::pair { "factory", "F|" }, std::pair { "user", "U|" } })
            if (auto* names = obj->getProperty (field).getArray())
                for (const auto& n : *names)
                    if (n.isString() && n.toString().isNotEmpty())
                        keys.addIfNotAlreadyThere (prefix + n.toString());
    return keys;
}

bool writeFavourites (const juce::File& file, const juce::StringArray& keys)
{
    juce::Array<juce::var> factory, user;
    for (const auto& k : keys)
        (k.startsWith ("F|") ? factory : user).add (k.substring (2));
    auto obj = std::make_unique<juce::DynamicObject>();
    obj->setProperty ("format", 1);
    obj->setProperty ("factory", factory);
    obj->setProperty ("user", user);
    return file.getParentDirectory().createDirectory() && file.replaceWithText (juce::JSON::toString (juce::var (obj.release())));
}

void markFavourites (std::vector<Kit>& kits, const juce::StringArray& keys)
{
    for (auto& k : kits)
        k.favourite = keys.contains (favouriteKey (k));
}

void moveFavourite (const juce::File& file, const juce::String& from, const juce::String& to)
{
    auto keys = readFavourites (file);
    if (! keys.contains (from) && (to.isEmpty() || ! keys.contains (to)))
        return;
    keys.removeString (from);
    if (to.isNotEmpty())
        keys.addIfNotAlreadyThere (to);
    writeFavourites (file, keys);
}
}

KitLibrary::KitLibrary (juce::File dir) : userDir (std::move (dir)) { rescan(); }

juce::File KitLibrary::defaultUserDirectory()
{
    return juce::File::getSpecialLocation (juce::File::userDocumentsDirectory).getChildFile ("PowerDrum/Kits");
}

juce::File KitLibrary::fileFor (const juce::String& name) const { return userDir.getChildFile (sanitiseName (name) + extension); }

void KitLibrary::rescan()
{
    kits = factoryKits();
    juce::Array<juce::File> files = userDir.findChildFiles (juce::File::findFiles, false, juce::String ("*") + extension);
    files.sort();
    for (const auto& f : files)
    {
        Kit k;
        juce::String err;
        if (kitFromXml (f.loadFileAsString(), k, err))
        {
            k.name = f.getFileNameWithoutExtension();
            k.category = "User";
            k.file = f;
            kits.push_back (std::move (k));
        }
    }
    markFavourites (kits, readFavourites (favouritesFile()));
}

int KitLibrary::indexOf (const juce::String& name) const
{
    for (size_t i = 0; i < kits.size(); ++i)
        if (kits[i].name == name)
            return (int) i;
    return -1;
}

bool KitLibrary::saveUser (const juce::String& name, const Snapshot& values, const std::array<juce::String, numSlots>& slotNames, juce::String& error)
{
    if (! userDir.createDirectory())
    {
        error = "Cannot create " + userDir.getFullPathName();
        return false;
    }
    const auto file = fileFor (name);
    const bool isNew = ! file.existsAsFile();
    if (! file.replaceWithText (kitToXml (sanitiseName (name), "User", values, slotNames)))
    {
        error = "Cannot write " + file.getFullPathName();
        return false;
    }
    if (isNew)
        moveFavourite (favouritesFile(), "U|" + file.getFileNameWithoutExtension(), {});
    rescan();
    return true;
}

bool KitLibrary::rename (int index, const juce::String& newName, juce::String& error)
{
    if (index < 0 || index >= (int) kits.size() || kits[(size_t) index].isFactory())
    {
        error = "Factory kits cannot be renamed";
        return false;
    }
    const auto target = fileFor (newName);
    if (target.existsAsFile())
    {
        error = "A kit with this name already exists";
        return false;
    }
    const auto& k = kits[(size_t) index];
    const auto old = k.file;
    if (! target.replaceWithText (kitToXml (sanitiseName (newName), "User", k.values, k.slotNames)) || ! old.deleteFile())
    {
        error = "Rename failed";
        return false;
    }
    moveFavourite (favouritesFile(), "U|" + old.getFileNameWithoutExtension(), "U|" + target.getFileNameWithoutExtension());
    rescan();
    return true;
}

bool KitLibrary::remove (int index, juce::String& error)
{
    if (index < 0 || index >= (int) kits.size() || kits[(size_t) index].isFactory())
    {
        error = "Factory kits cannot be deleted";
        return false;
    }
    const auto file = kits[(size_t) index].file;
    if (! moveToTrash (file))
    {
        error = "Could not move the kit to the Trash; nothing was deleted";
        return false;
    }
    moveFavourite (favouritesFile(), "U|" + file.getFileNameWithoutExtension(), {});
    rescan();
    return true;
}

bool KitLibrary::toggleFavourite (int index)
{
    if (index < 0 || index >= (int) kits.size())
        return false;
    auto keys = readFavourites (favouritesFile());
    const auto key = favouriteKey (kits[(size_t) index]);
    const bool on = ! keys.contains (key);
    if (on) keys.add (key); else keys.removeString (key);
    if (writeFavourites (favouritesFile(), keys))
        markFavourites (kits, keys);
    else
        markFavourites (kits, readFavourites (favouritesFile()));
    return kits[(size_t) index].favourite;
}

bool KitLibrary::importFile (const juce::File& source, juce::String& importedName, juce::String& error)
{
    Kit k;
    if (! kitFromXml (source.loadFileAsString(), k, error))
        return false;
    auto name = k.name.isNotEmpty() ? k.name : source.getFileNameWithoutExtension();
    for (int n = 2; fileFor (name).existsAsFile() || indexOf (name) >= 0; ++n)
        name = k.name + " " + juce::String (n);
    importedName = name;
    return saveUser (name, k.values, k.slotNames, error);
}

bool KitLibrary::exportTo (const juce::File& target, const juce::String& name, const Snapshot& values,
                           const std::array<juce::String, numSlots>& slotNames, juce::String& error) const
{
    if (! target.replaceWithText (kitToXml (sanitiseName (name), "User", values, slotNames)))
    {
        error = "Cannot write " + target.getFullPathName();
        return false;
    }
    return true;
}

