SoundLibrary::SoundLibrary (juce::File dir) : userDir (std::move (dir)) { rescan(); }

juce::File SoundLibrary::defaultUserDirectory()
{
    return juce::File::getSpecialLocation (juce::File::userDocumentsDirectory).getChildFile ("PowerDrum/Sounds");
}

void SoundLibrary::rescan()
{
    sounds = factorySounds();
    juce::Array<juce::File> files = userDir.findChildFiles (juce::File::findFiles, false, juce::String ("*") + extension);
    files.sort();
    for (const auto& f : files)
    {
        Sound s;
        juce::String err;
        if (soundFromXml (f.loadFileAsString(), s, err))
        {
            s.name = f.getFileNameWithoutExtension();
            s.kit = "My sounds";
            s.file = f;
            sounds.push_back (std::move (s));
        }
    }
}

std::vector<int> SoundLibrary::ofType (DrumType t) const
{
    std::vector<int> out;
    for (int i = 0; i < (int) sounds.size(); ++i)
        if (sounds[(size_t) i].type == t)
            out.push_back (i);
    return out;
}

int SoundLibrary::indexOf (const juce::String& name, DrumType t) const
{
    for (int i = 0; i < (int) sounds.size(); ++i)
        if (sounds[(size_t) i].type == t && sounds[(size_t) i].name == name)
            return i;
    return -1;
}

bool SoundLibrary::saveUser (const juce::String& name, const Snapshot& values, juce::String& error)
{
    if (! userDir.createDirectory())
    {
        error = "Cannot create " + userDir.getFullPathName();
        return false;
    }
    const auto file = userDir.getChildFile (sanitiseName (name) + extension);
    if (! file.replaceWithText (soundToXml (sanitiseName (name), values)))
    {
        error = "Cannot write " + file.getFullPathName();
        return false;
    }
    rescan();
    return true;
}
